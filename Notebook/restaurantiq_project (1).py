"""# Recommendation quality evaluation

There is an important conceptual issue here.

A recommendation system needs some notion of **relevance**.

We don't have explicit user ratings/preferences in this dataset, so we cannot honestly claim:

> "The recommender has 95% accuracy."

That would be fabricated.

Instead, we can perform **rule-based offline evaluation**.

For each recommendation, check:

### Criterion 1 — Cuisine relevance

Does the restaurant contain the requested cuisine?

### Criterion 2 — Rating requirement

Does:

```text id="q5w8p2"
Aggregate rating ≥ minimum rating
```

### Criterion 3 — Price constraint

Does:

```text id="a1k7mz"
Price range ≤ user's maximum
```

### Criterion 4 — Delivery requirement

Does the restaurant provide delivery when requested?

### Recommendation evaluation
"""

# ============================================================
# TASK 2 - FINAL RECOMMENDATION EVALUATION
# ============================================================

def evaluate_recommendations_final(
    recommendations,
    requested_cuisine=None,
    preferred_price_range=None,
    min_rating=0,
    online_delivery=None
):

    evaluation = recommendations.copy()

    # --------------------------------------------------------
    # 1. Cuisine relevance
    # --------------------------------------------------------

    if requested_cuisine is not None:

        requested_terms = [
            x.strip().lower()
            for x in requested_cuisine.split(",")
        ]

        evaluation["Cuisine Relevant"] = (
            evaluation["Cuisines"]
            .fillna("")
            .str.lower()
            .apply(
                lambda x: any(
                    term in x
                    for term in requested_terms
                )
            )
        )

    else:

        evaluation["Cuisine Relevant"] = True

    # --------------------------------------------------------
    # 2. Minimum rating requirement
    # --------------------------------------------------------

    evaluation["Rating Requirement"] = (
        evaluation["Aggregate rating"] >= min_rating
    )

    # --------------------------------------------------------
    # 3. Price compatibility
    #
    # SOFT PREFERENCE - NOT A HARD REQUIREMENT
    # --------------------------------------------------------

    if preferred_price_range is not None:

        evaluation["Price Compatibility"] = (
            1 -
            (
                abs(
                    evaluation["Price range"]
                    - preferred_price_range
                ) / 3
            )
        ).clip(lower=0)

    else:

        evaluation["Price Compatibility"] = 1.0

    # --------------------------------------------------------
    # 4. Online delivery requirement
    # --------------------------------------------------------

    if online_delivery is not None:

        evaluation["Delivery Requirement"] = (
            evaluation["Has Online delivery"]
            .str.lower()
            == online_delivery.lower()
        )

    else:

        evaluation["Delivery Requirement"] = True

    # --------------------------------------------------------
    # 5. HARD-CONSTRAINT SATISFACTION
    #
    # Price is deliberately excluded because it is
    # a soft preference.
    # --------------------------------------------------------

    evaluation["Meets Hard Criteria"] = (
        evaluation["Cuisine Relevant"]
        &
        evaluation["Rating Requirement"]
        &
        evaluation["Delivery Requirement"]
    )

    return evaluation

